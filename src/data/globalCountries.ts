/**
 * Find country by 2-letter or 3-letter code (case-insensitive)
 */
export function getCountryByCode(code: string): GlobalCountry | undefined {
  const c = code.trim().toUpperCase();
  return GLOBAL_COUNTRIES.find((item) => item.code === c || item.code3 === c);
}

/**
 * Search countries by name, code, or region
 */
export function searchCountries(query: string): GlobalCountry[] {
  const q = query.trim().toLowerCase();
  if (!q) return GLOBAL_COUNTRIES;
  return GLOBAL_COUNTRIES.filter(
    (c) =>
      c.name.toLowerCase().includes(q) ||
      c.nameBn.toLowerCase().includes(q) ||
      c.code.toLowerCase().includes(q) ||
      c.code3.toLowerCase().includes(q) ||
      c.region.toLowerCase().includes(q) ||
      c.continent.toLowerCase().includes(q)
  );
}

/**
 * Filter countries by continent
 */
export function getCountriesByContinent(continent: string): GlobalCountry[] {
  if (continent === 'All' || !continent) return GLOBAL_COUNTRIES;
  return GLOBAL_COUNTRIES.filter((c) => c.continent === continent);
}
